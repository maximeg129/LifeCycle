"use client"

import { useEffect, useMemo, useRef } from 'react'
import Link from 'next/link'
import { Skeleton } from '@/components/ui/skeleton'
import { ChevronRight } from 'lucide-react'
import { format } from 'date-fns'
import { useTrainingPlan } from './use-training-plan'
import { currentPlanWeek, computePlanProgress, PHASE_LABELS } from './training-plan-types'
import { PlanNextSessionsList } from './plan-next-sessions-list'
import { DailyWorkoutTab } from './daily-workout-tab'
import { PendingFeedbackBanner } from '@/components/coach/pending-feedback-banner'
import { TodayGreeting } from './today-greeting'

// ── Contexte plan sur Aujourd'hui (malgré le nom du fichier/de la
// fonction, conservés pour ne pas re-churner tous les imports/commentaires
// qui y font référence ailleurs dans la base) ───────────────────────────
//
// Refonte UI/IA (LifeCycle_Pro_UX_Engine_Review.md §3.1/3.3) : la gestion
// complète du plan (progression, "Pourquoi ce plan ?", vigilance, grille
// 12 semaines, prévu/réalisé, journal des recalibrations) a déménagé vers
// sa propre page top-level (/plan, voir plan-tab.tsx) — ce composant ne
// garde plus que ce que le brief UI appelle le "Plan header" : TodayGreeting
// ("Bonjour {Prénom}") + une seule ligne à droite ("Semaine 7/12 · Build ·
// 47 j avant le test FTP · Voir le plan ›", sur la MÊME rangée — restructuration
// lifecycle-ui-reference.html, retour utilisateur captures d'écran), plus la
// séance du jour elle-même (DailyWorkoutTab) et les 7 prochains jours
// (PlanNextSessionsList) — inclut désormais le jour "Aujourd'hui" lui-même
// dans la bande (voir le commentaire de tête de plan-next-sessions-list.tsx,
// "make the Aujourd'hui page as the attached" : la référence montre la tuile
// du jour surlignée dans la bande, à côté de la grande carte "séance du
// jour" juste au-dessus — redondant mais intentionnel), puis "À noter"
// (PendingFeedbackBanner) tout en bas — même position que dans la référence.
// Rendu directement sur /cycling (voir ce fichier), qui devient ainsi
// "Aujourd'hui" au sens de la nouvelle IA.
export function TrainingPlanTab() {
  const {
    activePlan, isLoadingPlan,
    generateWeekSessions, generatingSessionsForWeek, moveSessionDate, adjustSessionForLocation, adjustingLocationKey,
    addStrengthExercise, addStrengthExerciseSet,
    getSessionCompletion, sendSessionToIntervals, sendingSessionKey, canSendToIntervals,
    activities, athleteFtp,
  } = useTrainingPlan()
  const today = format(new Date(), 'yyyy-MM-dd')
  const week = activePlan ? currentPlanWeek(activePlan.weeks, today) : null

  const currentWeekCompletions = useMemo(
    () => (week && week.sampleSessions ? week.sampleSessions.map((s, i) => getSessionCompletion(week, s, i)) : []),
    [week, getSessionCompletion]
  )
  const planProgress = activePlan ? computePlanProgress(activePlan, week, currentWeekCompletions, today) : null

  // Même garde qu'avant l'extraction (plan-tab.tsx a sa propre copie
  // identique pour SA vue — deux instances indépendantes de useTrainingPlan()
  // sur deux routes séparées, chacune doit pouvoir déclencher cette
  // génération si l'athlète n'ouvre que l'une des deux pages).
  const autoGeneratedRef = useRef<number | null>(null)
  useEffect(() => {
    if (!week || week.sampleSessions || generatingSessionsForWeek != null) return
    if (autoGeneratedRef.current === week.weekNumber) return
    autoGeneratedRef.current = week.weekNumber
    generateWeekSessions(week)
  }, [week, generatingSessionsForWeek, generateWeekSessions])

  // En-tête "Bonjour {Prénom}" + "Semaine N/T · Phase · Jj avant l'objectif
  // ›" sur la MÊME rangée (restructuration lifecycle-ui-reference.html,
  // retour utilisateur captures d'écran) — TodayGreeting déménagé ici
  // depuis cycling/page.tsx (qui ne fait plus que l'appeler) pour vivre à
  // côté de ce lien sans ouvrir une deuxième instance de useTrainingPlan()
  // juste pour aligner les deux visuellement. Rendu AVANT le early-return
  // isLoadingPlan pour que la salutation reste visible immédiatement, sans
  // attendre le premier chargement du plan.
  const header = (
    <div className="flex items-start justify-between gap-4 flex-wrap">
      <TodayGreeting />
      {activePlan && (
        <Link
          href="/plan"
          className="flex items-center gap-1 text-sm text-muted-foreground hover:text-foreground transition-colors group shrink-0"
        >
          <span className="truncate">
            Semaine {week?.weekNumber ?? '—'}/{activePlan.weeks.length}
            {week && ` · ${PHASE_LABELS[week.phase]}`}
            {planProgress && planProgress.daysRemaining >= 0 && ` · ${planProgress.daysRemaining} j avant l'objectif`}
          </span>
          <span className="flex items-center gap-0.5 shrink-0 font-medium">
            Voir le plan <ChevronRight className="w-3.5 h-3.5 group-hover:translate-x-0.5 transition-transform" />
          </span>
        </Link>
      )}
    </div>
  )

  if (isLoadingPlan) {
    return (
      <div className="space-y-6">
        {header}
        <Skeleton className="h-48 w-full rounded-2xl" />
      </div>
    )
  }

  return (
    <div className="space-y-6">
      {header}

      <DailyWorkoutTab />

      {activePlan && (
        <PlanNextSessionsList
          weeks={activePlan.weeks}
          today={today}
          generatingSessionsForWeek={generatingSessionsForWeek}
          sendingSessionKey={sendingSessionKey}
          canSendToIntervals={canSendToIntervals}
          onRegenerate={(w) => generateWeekSessions(w)}
          onSend={(w, session, index, dateId) => sendSessionToIntervals(session, w.weekNumber, index, dateId)}
          onMoveDate={(w, index, newDate) => moveSessionDate(w.weekNumber, index, newDate)}
          getCompletion={(w, session, index) => getSessionCompletion(w, session, index)}
          adjustingLocationKey={adjustingLocationKey}
          onAdjustLocation={(w, index, targetLocation) => adjustSessionForLocation(w.weekNumber, index, targetLocation)}
          onAddExercise={(w, index, exercise) => addStrengthExercise(w.weekNumber, index, exercise)}
          onAddExerciseSet={(w, index, exerciseIndex) => addStrengthExerciseSet(w.weekNumber, index, exerciseIndex)}
          activities={activities}
          athleteFtp={athleteFtp}
        />
      )}

      {/* "À noter" (RPE manquants) — déplacé en bas de l'écran (restructuration
          lifecycle-ui-reference.html) : la référence le montre après "Cette
          semaine", pas entre la salutation et la séance du jour. */}
      <PendingFeedbackBanner />
    </div>
  )
}
